"""Benchmark one model on the fixed demo questions and append the runs to the run log.

    python -m demo_app.bench --label "stock 4B" --provider vllm \\
        --base-url http://localhost:11434/v1 --model nemotron-3-nano:4b
    python -m demo_app.bench --label "trained 4B" --provider vllm \\
        --base-url http://localhost:11434/v1 --model <your-trained-model>
    python -m demo_app.bench --summary          # compare everything logged so far
    python -m demo_app.bench --export demo_app/baselines/2026-10-17   # save runs + summary to commit

Questions come from the evaluation bank (q02, q05, q07, q13, q15), so every run gets a verifier reward.
--suite kb adds the regulatory-agent and scenario-factor questions (runlog.KB_QUESTIONS).
Runs go one at a time; on a 16 GB laptop keep other heavy apps closed.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from demo_app.runlog import ask, bench_questions, load_runs, runs_path, summary  # noqa: E402


def print_summary() -> None:
    rows = summary(load_runs())
    if not rows:
        print("no runs logged yet")
        return
    cols = ["label", "runs", "median_duration_s", "median_llm_s", "mean_llm_turns", "mean_tool_calls",
            "median_tokens_per_s", "grounded_pct", "mean_reward"]
    print(" | ".join(cols))
    for r in rows:
        print(" | ".join(str(r[c]) for c in cols))


COLUMNS = [("label", "Label"), ("model", "Model"), ("runs", "Runs"), ("median_duration_s", "Median time (s)"),
           ("median_llm_s", "Median model time (s)"), ("mean_llm_turns", "Model turns"),
           ("mean_tool_calls", "Tool calls"), ("median_tokens_per_s", "Tokens/s"),
           ("grounded_pct", "No unsupported numbers %"), ("mean_reward", "Mean quality (0-1)")]


def export(folder: Path, only: list[str] | None = None) -> None:
    """Write runs.jsonl (logged runs, optionally only some labels) and SUMMARY.md (per-model table + per-question detail)."""
    runs = [r for r in load_runs() if not only or r["label"] in only]
    folder.mkdir(parents=True, exist_ok=True)
    with open(folder / "runs.jsonl", "w") as fh:
        fh.writelines(json.dumps(r, default=str) + "\n" for r in runs)
    lines = ["# Model run baseline", "",
             "Generated by `python -m demo_app.bench --export`. Quality = Gym verifier reward (0-1) on evaluation-bank "
             "questions: correct facts, grounding, tool choice, valid calls, efficiency. Model time = waiting on the "
             "model; the rest is the deterministic tools.", "",
             "| " + " | ".join(h for _, h in COLUMNS) + " |", "|" + "---|" * len(COLUMNS)]
    lines += ["| " + " | ".join(str(r[k]) if r[k] is not None else "-" for k, _ in COLUMNS) + " |" for r in summary(runs)]
    lines += ["", "## Per question", "", "| Label | Question | Time (s) | Model (s) | Turns | Tools used | Grounding | Quality | Facts |",
              "|---|---|---|---|---|---|---|---|---|"]
    for r in runs:
        q = r.get("quality") or {}
        facts = f"{q['checks_passed']}/{q['checks_total']}" if q else "-"
        lines.append(f"| {r['label']} | {r['question']} | {r['duration_s']} | {r['llm_s']} | {r['llm_turns']} | "
                     f"{', '.join(r['tools_used']) or '-'} | {r['grounding']} | {q.get('reward', '-')} | {facts} |")
    (folder / "SUMMARY.md").write_text("\n".join(lines) + "\n")
    print(f"exported {len(runs)} runs to {folder}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--label", help="name shown in the comparison, e.g. 'stock 4B'")
    ap.add_argument("--provider", choices=["mock", "vllm", "nvidia", "openai"])
    ap.add_argument("--base-url")
    ap.add_argument("--model")
    ap.add_argument("--mode", choices=["team", "orchestrator"], default="orchestrator")
    ap.add_argument("--thinking", action="store_true", help="leave reasoning on (slower)")
    ap.add_argument("--repeats", type=int, default=1)
    ap.add_argument("--suite", choices=["core", "kb", "all"], default="core",
                    help="core = 5 allowance questions (baseline); kb = regulatory + factor questions (needs scripts.load_kb)")
    ap.add_argument("--summary", action="store_true")
    ap.add_argument("--export", type=Path, help="write runs.jsonl + SUMMARY.md to this folder")
    ap.add_argument("--only", action="append", help="with --export: only runs with this label (repeatable)")
    a = ap.parse_args()
    if a.export:
        export(a.export, a.only)
        return
    if a.summary:
        print_summary()
        return
    overrides = {"provider": a.provider, "base_url": a.base_url, "model": a.model,
                 "enable_thinking": True if a.thinking else False}
    questions = bench_questions(a.suite)
    for rep in range(a.repeats):
        for i, q in enumerate(questions, 1):
            _, rec = ask(q, a.mode, overrides, a.label, source="bench")
            qual = rec["quality"] or {}
            print(f"[{rep + 1}.{i}/{len(questions)}] {rec['duration_s']:6.1f}s  reward={qual.get('reward')}  "
                  f"grounding={rec['grounding']}  tools={rec['tools_used']}  | {q}", flush=True)
    print(f"\nlogged to {runs_path()}\n")
    print_summary()


if __name__ == "__main__":
    main()
